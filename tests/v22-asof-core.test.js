'use strict';
const assert=require('node:assert/strict');
const {buildAsOf,atOrBefore,build4h,coverage,dateMs,fmt}=require('../lib/endpoints/v22-asof-core');
const seq=buildAsOf([{date:'2025-03-03',value:1},{date:'2025-03-04',value:2}],3).rows;
assert.equal(atOrBefore(seq,dateMs('2025-03-05')),null);
assert.equal(atOrBefore(seq,dateMs('2025-03-06')).value,1);
assert.equal(atOrBefore(seq,dateMs('2025-03-07')).value,2);
const duplicates=buildAsOf([{date:'2025-03-03',value:1},{date:'2025-03-03',value:2}],3);
assert.equal(duplicates.rows.length,0);
assert.deepEqual(fmt(dateMs('2025-03-10')+22*3600000),{date:'2025-03-10',hour:18});
const h=3600000,s=dateMs('2025-03-10')+22*h;
const ohlc=Array.from({length:4},(_,i)=>({t:s+i*h,o:100+i,h:102+i,l:99+i,c:101+i}));
let built=build4h(ohlc,dateMs('2025-03-12'));
assert.equal(built.candles.length,1);
assert.equal(built.candles[0].close_ms,s+4*h);
const avail=buildAsOf([{date:'2025-03-09',value:45}],1);
const result=coverage(built.candles,{X:avail},['X']);
assert.equal(result.future_time_violations,0);
assert.equal(result.complete,1);
const dupe=build4h([...ohlc,ohlc[1]],dateMs('2025-03-12'));
assert.equal(dupe.candles.length,0);
assert.equal(dupe.quality.duplicate_hours,2);
console.log('All V2.2 as-of core tests passed');
